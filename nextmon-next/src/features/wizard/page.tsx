import { Icon } from '../../components/Icon';
import { Routers } from '../../lib/routers.ts';
import { Scripts } from '../../lib/scripts.ts';
import type { PageProps } from '../types.ts';
import ActionForm from '../routers/ActionForm';
import { NetAssets, Badge, Empty, PageHead } from '../_netkit/ui.tsx';
import { portalHost, runWizardAction, useWizardUserAction } from './actions.ts';
import { logRows, pageParams, savedCred, savedOut, STEPS } from './logic.ts';
import type { OpRow, Status } from './logic.ts';
import { templateDir, templateFiles } from './template.ts';

const KIND: Record<Status, 'ok' | 'warn' | 'err' | 'info' | 'neutral'> = { ok: 'ok', warn: 'warn', err: 'err', plan: 'info', skip: 'neutral' };
const LABEL: Record<string, string> = { ok: 'OK', warn: 'Check', err: 'Failed', plan: 'Planned', skip: 'Skipped' };

const INFO: Record<string, [string, string]> = {
  check: ['Connectivity check', 'Read-only: confirms NextMON can talk to the router and reports version, hotspot, API services, clock and existing NextMON users.'],
  user: ['Least-privilege API user', 'Creates a group with only the rights NextMON needs and a dedicated API user (docs/mikrotik-scripts/07). Better than using admin.'],
  services: ['API services', 'Enables the API (and optionally API-SSL with a self-signed certificate) and can limit it to the NextMON server address (docs/06).'],
  scripts: ['On-login and expiry scripts', 'Installs the hourly cleanup script and writes the voucher on-login script on the hotspot profiles you tick (generated by NextMON, Mikhmon compatible).'],
  walled: ['Walled garden defaults', 'Lets guests reach the portal, payment gateways and captive-portal checks without logging in (docs/08). Existing entries are never duplicated.'],
  ntp: ['Clock and NTP', 'Voucher expiry is calculated from the router clock, so NTP/SNTP must be running.'],
  template: ['Hotspot login template', 'RouterOS API cannot upload files, so upload the template folder yourself (WinBox, FTP or SCP), then verify it here and point the hotspot profile to it.'],
};

const OL_MODES: [string, string][] = [
  ['remc', 'remc - remove on expiry and record the sale'],
  ['rem', 'rem - remove on expiry'],
  ['ntfc', 'ntfc - keep, block login, record the sale'],
  ['ntf', 'ntf - keep and block login'],
  ['none', 'none'],
];

const UPLOAD_HELP = `WinBox:  Files > drag the hotspot-nextmon folder in
FTP:     /ip service enable ftp   (disable it again afterwards)
         ftp <router-ip>; mkdir hotspot-nextmon; cd hotspot-nextmon; put login.html ... (keep css/ js/ img/)
SCP:     scp -r hotspot-nextmon admin@<router-ip>:/
Flash:   routers with a flash folder: use flash/hotspot-nextmon`;

/** Setup wizard: prepare the current router for NextMON, step by step (preview first, then apply). */
export default async function WizardPage({ ctx }: PageProps) {
  const t = ctx.t;
  const router = ctx.router;
  const csrf = <input type="hidden" name="_csrf" value={ctx.csrf} />;
  const head = <PageHead title={t('Setup wizard')} desc={t('Prepare a router for NextMON step by step. Every step can be previewed first: nothing is sent until you apply it.')} />;
  if (!router) {
    return (
      <>
        <NetAssets />
        {head}
        <section className="card glass">
          <Empty icon="router" title={t('This account has no router yet. Ask the account owner to add one.')}>
            <a className="btn btn-primary" href="/routers">
              {t('Add router')}
            </a>
          </Empty>
        </section>
      </>
    );
  }

  const readOnly = router.shared && router.mode === 'ro';
  let profiles: { name: string; meta: ReturnType<typeof Scripts.parseMeta>; has: boolean }[] = [];
  let hsProfiles: string[] = [];
  let error = '';
  try {
    const d = ctx.driver();
    profiles = (await d.print('/ip/hotspot/user/profile', {}, ['name', 'on-login'])).map((p) => ({ name: p.name ?? '', meta: Scripts.parseMeta(p['on-login'] ?? ''), has: (p['on-login'] ?? '').trim() !== '' }));
    hsProfiles = (await d.print('/ip/hotspot/profile', {}, ['name'])).map((p) => p.name ?? '');
  } catch (e) {
    error = (e as Error).message;
  }
  const p = pageParams(await portalHost());
  const out = savedOut(router.id);
  const cred = savedCred(router.id);
  const log = logRows(router.id);
  const tdir = templateDir();
  const tplFiles = tdir ? Object.keys(templateFiles(tdir)) : [];
  const current = Routers.get(router.id) ?? router;

  const renderOut = (step: string) => {
    if (!out || out.step !== step) return null;
    return (
      <div className="nm-log" role="status" aria-live="polite">
        <div>
          <b>{out.mode === 'apply' ? t('Result') : t('Commands that would run (nothing was sent)')}</b>
        </div>
        {out.rows.map((r: OpRow, i: number) => (
          <div key={i} style={{ display: 'contents' }}>
            <div style={{ flexWrap: 'wrap' }}>
              <Badge kind={KIND[r.status]}>{t(LABEL[r.status] ?? r.status)}</Badge> <b>{r.label}</b>
              {r.msg !== '' ? <span className="muted">{r.msg}</span> : null}
            </div>
            <div style={{ paddingLeft: 'var(--s4)' }}>
              <code className="mono muted" style={{ fontSize: 'var(--fs-12)', overflowWrap: 'anywhere' }}>
                {r.cli}
              </code>
            </div>
            {r.detail !== '' ? (
              <details style={{ paddingLeft: 'var(--s4)' }}>
                <summary className="muted">{t('Show script')}</summary>
                <pre className="nm-pre" tabIndex={0}>
                  {r.detail}
                </pre>
              </details>
            ) : null}
          </div>
        ))}
      </div>
    );
  };

  return (
    <>
      <NetAssets />
      {head}

      <div className="alert info" style={{ marginBottom: 'var(--s4)' }}>
        <Icon name="router" size={18} />
        <div style={{ flex: 1 }}>
          {t('Router')}: <b>{current.name}</b>
          {ctx.demo ? ' (demo)' : ''}
          {error ? (
            <>
              <br />
              <span className="muted">{t('Could not read the router right now: :e', { ':e': error })}</span>
            </>
          ) : null}
          {readOnly ? (
            <>
              <br />
              <span className="muted">{t('This shared router is read-only.')}</span>
            </>
          ) : null}
          <br />
          <span className="muted">{t('Run this wizard with an administrator account on the router. Use "Show commands" to review, and keep a backup (Monitor > Backups) before applying.')}</span>
        </div>
      </div>

      <ol className="nm-steps">
        {STEPS.map((s) => (
          <li className="nm-step" id={`s-${s}`} key={s}>
            <div className="nm-step-h">
              <h2>{t(INFO[s]![0])}</h2>
            </div>
            <div className="nm-step-b">
              <p className="muted" style={{ margin: 0 }}>
                {t(INFO[s]![1])}
              </p>
              <ActionForm action={runWizardAction} className="stack">
                {csrf}
                <input type="hidden" name="step" value={s} />

                {s === 'user' ? (
                  <>
                    <div className="form-grid">
                      <div className="field">
                        <label htmlFor="w-ip">{t('NextMON server address')}</label>
                        <input className="input mono" id="w-ip" name="server_ip" defaultValue={p.server_ip} placeholder="192.168.88.10 or 192.168.88.0/24" />
                        <p className="help">{t('Optional but recommended: the user can log in only from here.')}</p>
                      </div>
                      <div className="field">
                        <label htmlFor="w-user">{t('API user name')}</label>
                        <input className="input mono" id="w-user" name="api_user" defaultValue={p.api_user} maxLength={32} />
                      </div>
                      <div className="field full">
                        <label htmlFor="w-lvl">{t('Access level')}</label>
                        <select className="select" id="w-lvl" name="level" defaultValue={p.level}>
                          <option value="op">{t('Operator (read, write, api, test, policy) - needed for vouchers and on-login scripts')}</option>
                          <option value="ro">{t('Read-only (read, api) - dashboard and monitor only')}</option>
                        </select>
                      </div>
                    </div>
                    <label className="check">
                      <input type="checkbox" name="ack_resetuser" value="1" />
                      {t('If the user already exists, reset its password (extra confirmation)')}
                    </label>
                  </>
                ) : null}

                {s === 'services' ? (
                  <>
                    <div className="form-grid">
                      <div className="field">
                        <label htmlFor="w-ip2">{t('Allow API only from')}</label>
                        <input className="input mono" id="w-ip2" name="server_ip" defaultValue={p.server_ip} placeholder="192.168.88.10 or 192.168.88.0/24" />
                        <p className="help">{t('Empty = leave the allowed addresses unchanged.')}</p>
                      </div>
                      <div className="field">
                        <label className="check" style={{ marginTop: 'var(--s5)' }}>
                          <input type="checkbox" name="ssl" value="1" defaultChecked={p.ssl === '1'} />
                          {t('Also enable API-SSL (creates a self-signed certificate; signing can take a while)')}
                        </label>
                      </div>
                    </div>
                    <label className="check">
                      <input type="checkbox" name="ack_lockout" value="1" />
                      {t('I know that limiting the API to an address blocks NextMON if it connects from a different address (extra confirmation)')}
                    </label>
                  </>
                ) : null}

                {s === 'scripts' ? (
                  <>
                    <div className="form-grid">
                      <div className="field">
                        <label htmlFor="w-mode">{t('Mode')}</label>
                        <select className="select" id="w-mode" name="ol_mode" defaultValue={p.mode}>
                          {OL_MODES.map(([k, l]) => (
                            <option key={k} value={k}>
                              {l}
                            </option>
                          ))}
                        </select>
                      </div>
                      <div className="field">
                        <label className="check" style={{ marginTop: 'var(--s5)' }}>
                          <input type="checkbox" name="lock_user" value="1" defaultChecked={p.lock_user === '1'} />
                          {t('Lock the voucher to the first device (MAC)')}
                        </label>
                      </div>
                    </div>
                    {profiles.length > 0 ? (
                      <>
                        <div className="table-wrap">
                          <table className="tbl resp">
                            <thead>
                              <tr>
                                <th className="cell-chk">
                                  <span className="sr-only">{t('Select')}</span>
                                </th>
                                <th>{t('Profile')}</th>
                                <th>{t('Current script')}</th>
                                <th>{t('Price')}</th>
                                <th>{t('Validity')}</th>
                              </tr>
                            </thead>
                            <tbody>
                              {profiles
                                .filter((pr) => !['default', 'default-encryption'].includes(pr.name))
                                .map((pr) => (
                                  <tr key={pr.name}>
                                    <td className="cell-chk" data-label="">
                                      <input type="checkbox" name="profiles[]" value={pr.name} aria-label={pr.name} />
                                    </td>
                                    <td data-label={t('Profile')}>{pr.name}</td>
                                    <td data-label={t('Current script')}>
                                      {pr.meta ? <Badge kind="info">{`${pr.meta.mode} / ${pr.meta.validity || '-'}`}</Badge> : pr.has ? <Badge kind="warn">{t('other script')}</Badge> : <Badge>{t('none')}</Badge>}
                                    </td>
                                    <td data-label={t('Price')}>
                                      <input className="input input-sm mono" name={`price[${pr.name}]`} aria-label={`${t('Price')} ${pr.name}`} defaultValue={pr.meta?.price ?? ''} inputMode="numeric" style={{ maxWidth: 120 }} />
                                    </td>
                                    <td data-label={t('Validity')}>
                                      <input className="input input-sm mono" name={`validity[${pr.name}]`} aria-label={`${t('Validity')} ${pr.name}`} defaultValue={pr.meta?.validity ?? ''} placeholder="1d" style={{ maxWidth: 100 }} autoCapitalize="off" />
                                    </td>
                                  </tr>
                                ))}
                            </tbody>
                          </table>
                        </div>
                        <label className="check">
                          <input type="checkbox" name="ack_overwrite" value="1" />
                          {t('Replace on-login scripts that already exist on ticked profiles (extra confirmation)')}
                        </label>
                      </>
                    ) : (
                      <p className="help">{t('No profiles could be read. Only the cleanup script will be installed.')}</p>
                    )}
                  </>
                ) : null}

                {s === 'walled' ? (
                  <div className="form-grid">
                    <div className="field">
                      <label htmlFor="w-portal">{t('NextMON portal host')}</label>
                      <input className="input mono" id="w-portal" name="portal" defaultValue={p.portal} placeholder="nextmon.example.com" />
                      <p className="help">{t('Adds this host plus Midtrans, Xendit, Tripay and captive-portal checks.')}</p>
                    </div>
                  </div>
                ) : null}

                {s === 'ntp' ? (
                  <>
                    <div className="form-grid">
                      <div className="field">
                        <label htmlFor="w-ntp">{t('NTP servers')}</label>
                        <input className="input mono" id="w-ntp" name="ntp_servers" defaultValue={p.ntp_servers} />
                      </div>
                      <div className="field">
                        <label htmlFor="w-tz">{t('Time zone')}</label>
                        <input className="input mono" id="w-tz" name="tz" defaultValue={p.tz} placeholder="Asia/Jakarta" />
                        <p className="help">{t('Empty = do not change.')}</p>
                      </div>
                    </div>
                    <label className="check">
                      <input type="checkbox" name="ack_tz" value="1" />
                      {t('Allow changing the time zone (extra confirmation)')}
                    </label>
                  </>
                ) : null}

                {s === 'template' ? (
                  <div className="stack">
                    {tdir ? (
                      <div>
                        <b>{t('Files to upload')}</b> <span className="muted">({tplFiles.length})</span>
                        <div className="nm-pre" tabIndex={0} style={{ maxHeight: 140 }}>
                          {tplFiles.join('\n')}
                        </div>
                        <a className="btn btn-sm" style={{ marginTop: 'var(--s2)' }} href="/api/json/wizard/template.zip" download>
                          <Icon name="download" size={16} />
                          {t('Download hotspot-nextmon.zip')}
                        </a>
                      </div>
                    ) : (
                      <p className="help">{t('The shared/hotspot-login folder was not found next to this installation.')}</p>
                    )}
                    <div>
                      <b>{t('Upload options (pick one)')}</b>
                      <pre className="nm-pre" tabIndex={0}>
                        {UPLOAD_HELP}
                      </pre>
                    </div>
                    <div className="form-grid">
                      <div className="field">
                        <label htmlFor="w-dir">{t('Folder on the router')}</label>
                        <input className="input mono" id="w-dir" name="html_dir" defaultValue={p.html_dir} />
                      </div>
                      <div className="field">
                        <label htmlFor="w-hsp">{t('Hotspot profile to switch (optional)')}</label>
                        <select className="select" id="w-hsp" name="hs_profile" defaultValue={p.hs_profile}>
                          <option value="">{t('(only verify the upload)')}</option>
                          {hsProfiles.map((h) => (
                            <option key={h}>{h}</option>
                          ))}
                        </select>
                      </div>
                    </div>
                    <label className="check">
                      <input type="checkbox" name="ack_htmldir" value="1" />
                      {t('Switch the live login page of that profile (extra confirmation)')}
                    </label>
                  </div>
                ) : null}

                <div className="row" style={{ flexWrap: 'wrap' }}>
                  <button className="btn" name="mode" value="preview">
                    <Icon name="terminal" size={16} />
                    {t('Show commands')}
                  </button>
                  {s === 'check' ? (
                    <button className="btn btn-primary" name="mode" value="apply" disabled={readOnly}>
                      <Icon name="check" size={16} />
                      {t('Run check')}
                    </button>
                  ) : (
                    <>
                      <label className="check">
                        <input type="checkbox" name="confirm" value="1" />
                        {t('I reviewed the commands and want to apply them')}
                      </label>
                      <button className="btn btn-primary" name="mode" value="apply" disabled={readOnly}>
                        <Icon name="check" size={16} />
                        {t('Apply')}
                      </button>
                    </>
                  )}
                </div>
              </ActionForm>

              {s === 'user' && cred && !router.shared ? (
                <div className="alert warn">
                  <Icon name="key" size={18} />
                  <div style={{ flex: 1 }}>{t('A new password was generated for user :u. NextMON can store it for this router, so you never need to see it.', { ':u': cred.user })}</div>
                  <ActionForm action={useWizardUserAction}>
                    {csrf}
                    <input type="hidden" name="confirm" value="1" />
                    <button className="btn btn-sm" data-confirm={t('Switch NextMON to the new API user for this router?')}>
                      {t('Use this user in NextMON')}
                    </button>
                  </ActionForm>
                </div>
              ) : null}

              {renderOut(s)}
            </div>
          </li>
        ))}
      </ol>

      <section className="card glass" style={{ marginTop: 'var(--s5)' }}>
        <div className="card-h">
          <h2>{t('Applied commands log')}</h2>
        </div>
        {log.length === 0 ? (
          <Empty icon="terminal" title={t('Nothing applied yet')} />
        ) : (
          <div className="table-wrap" style={{ maxHeight: 420 }}>
            <table className="tbl resp">
              <thead>
                <tr>
                  <th>{t('Time')}</th>
                  <th>{t('Step')}</th>
                  <th>{t('Command')}</th>
                  <th>{t('Result')}</th>
                </tr>
              </thead>
              <tbody>
                {log.map((l, i) => (
                  <tr key={i}>
                    <td data-label={t('Time')} className="mono nowrap">
                      {new Date(l.ts * 1000).toISOString().slice(5, 19).replace('T', ' ')}
                    </td>
                    <td data-label={t('Step')}>{l.step}</td>
                    <td data-label={t('Command')} className="wrap mono" style={{ fontSize: 'var(--fs-12)' }}>
                      {l.label}
                      <br />
                      <span className="muted">{l.cli}</span>
                    </td>
                    <td data-label={t('Result')} className="wrap">
                      <Badge kind={KIND[l.status as Status] ?? 'neutral'}>{t(LABEL[l.status] ?? l.status)}</Badge> <span className="muted">{l.msg}</span>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </section>
    </>
  );
}
