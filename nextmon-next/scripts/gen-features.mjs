#!/usr/bin/env node
/**
 * Feature discovery. Every directory src/features/<name>/ that contains a `feature.ts` is a feature module. This script writes
 * src/features/_generated.ts (git-ignored) importing them all, so feature authors NEVER edit a shared file.
 * Runs automatically before dev / build / lint / typecheck / test.  Pass --watch to regenerate when features are added/removed.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'src', 'features');
const target = path.join(dir, '_generated.ts');

export function generate() {
  const names = fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('_') && fs.existsSync(path.join(dir, e.name, 'feature.ts')))
    .map((e) => e.name)
    .sort();
  const ident = (n) => 'f_' + n.replace(/[^A-Za-z0-9]/g, '_');
  const body =
    '// AUTO-GENERATED by scripts/gen-features.mjs - do not edit, do not commit.\n' +
    "import type { Feature } from './types.ts';\n" +
    names.map((n) => `import ${ident(n)} from './${n}/feature.ts';`).join('\n') +
    `\n\nexport const generated: Feature[] = [${names.map(ident).join(', ')}];\n`;
  const prev = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (prev !== body) fs.writeFileSync(target, body);
  return names;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const names = generate();
  if (process.argv.includes('--watch')) {
    console.log('[features] watching src/features:', names.join(', '));
    let t;
    fs.watch(dir, { recursive: true }, (_ev, f) => {
      if (f && f.endsWith('_generated.ts')) return;
      clearTimeout(t);
      t = setTimeout(() => generate(), 150);
    });
  } else {
    console.log(`[features] ${names.length} feature(s): ${names.join(', ') || '-'}`);
  }
}
